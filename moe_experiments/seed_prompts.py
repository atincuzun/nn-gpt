"""Write the pinned CV seed list every experiment arm generates from.

``nn_gen`` reads it through the upstream seed-pinning hook
(``NNGPT_SEED_FILE`` + ``NNGPT_SEED_FILE_EXTERNAL=1``), so every arm, round
and replicate prompts the LLM with the same seed networks in the same order,
and per-prompt outcomes can be compared pairwise across arms.

Seeds are drawn once, reproducibly, from the LEMUR families the gate cycle
trains on, excluding models generated by earlier MoE-cycle runs, and limited
to code lengths that leave room for a full answer.

    python moe_experiments/seed_prompts.py --out out/moex/seed_prompts.json
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

EXCLUDED_PREFIXES = ("moe-", "moex", "xsi")


def build_seed_list(*, count: int, random_state: int, dataset: str,
                    min_chars: int, max_chars: int) -> dict:
    import ab.nn.api as lemur

    from moe_cycle.cli import GATE_CYCLE_NN_PREFIXES

    data = lemur.data(
        only_best_accuracy=True,
        task="img-classification",
        dataset=dataset,
        nn_prefixes=GATE_CYCLE_NN_PREFIXES,
    )
    if data.empty:
        raise RuntimeError("LEMUR returned no seed rows")
    names = data["nn"].astype(str)
    data = data[~names.str.lower().str.startswith(EXCLUDED_PREFIXES)]
    lengths = data["nn_code"].astype(str).str.len()
    data = data[(lengths >= min_chars) & (lengths <= max_chars)]
    best = (
        data.sort_values("accuracy", ascending=False)
        .groupby("nn", sort=True)
        .head(1)
        .sort_values("nn")
    )
    chosen = best.sample(n=min(count, len(best)), random_state=random_state)
    return {
        "nn": chosen["nn"].tolist(),
        "seed_accuracy": [round(float(value), 4) for value in chosen["accuracy"]],
        "selection": {
            "dataset": dataset,
            "families": "moe_cycle.cli.GATE_CYCLE_NN_PREFIXES",
            "excluded_prefixes": list(EXCLUDED_PREFIXES),
            "code_chars": [min_chars, max_chars],
            "candidates": int(len(best)),
            "random_state": random_state,
        },
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--count", type=int, default=64)
    parser.add_argument("--random-state", type=int, default=2026)
    parser.add_argument("--dataset", default="cifar-10")
    parser.add_argument("--min-chars", type=int, default=600)
    parser.add_argument("--max-chars", type=int, default=6000)
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()
    if args.out.is_file() and not args.force:
        print(f"[seeds] keeping existing {args.out}")
        return
    payload = build_seed_list(
        count=args.count,
        random_state=args.random_state,
        dataset=args.dataset,
        min_chars=args.min_chars,
        max_chars=args.max_chars,
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    accuracies = payload["seed_accuracy"]
    print(
        f"[seeds] {len(payload['nn'])} seeds -> {args.out} "
        f"(seed accuracy min={min(accuracies):.3f} "
        f"median={sorted(accuracies)[len(accuracies) // 2]:.3f} max={max(accuracies):.3f})"
    )


if __name__ == "__main__":
    main()
